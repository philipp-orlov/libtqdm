"""Write include/tqdm/unicode_tables.hpp from Python's Unicode database.

    python3 tools/gen_unicode_tables.py > include/tqdm/unicode_tables.hpp

A newer Python carries a newer Unicode version: rerun this to pick it up.
"""
import sys
import unicodedata


def ranges(predicate):
    out, start = [], None
    for cp in range(0x110000):
        if predicate(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def is_zero_width(cp):
    # Marks that sit on the previous cell, format characters, and the Hangul
    # medial and final jamo that compose into the leading one. U+00AD (soft
    # hyphen) is Cf but terminals give it a cell.
    if cp == 0xAD:
        return False
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF:
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")


def is_wide(cp):
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F") and not is_zero_width(cp)


def emit(name, table):
    print(f"inline constexpr Range {name}[] = {{")
    line = "   "
    for lo, hi in table:
        item = f" {{0x{lo:X}, 0x{hi:X}}},"
        if len(line) + len(item) > 100:
            print(line)
            line = "   "
        line += item
    print(line)
    print("};\n")


print(f"""// Copyright (c) 2026 Philipp Orlov
// SPDX-License-Identifier: Apache-2.0

#pragma once

// Generated by tools/gen_unicode_tables.py from Unicode {unicodedata.unidata_version}. Do not edit.
// Sorted, non-overlapping, inclusive code point ranges.

namespace tqdm::unicode::tables {{

struct Range {{
    char32_t first;
    char32_t last;
}};
""")
emit("kZeroWidth", ranges(is_zero_width))
emit("kWide", ranges(is_wide))
print("} // namespace tqdm::unicode::tables")
